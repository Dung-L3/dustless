import Foundation

/// UI language for the native app. Mirrors `src/ui/public/i18n.js`, which the
/// web UI uses, so both surfaces share one vocabulary.
public enum Lang: String, CaseIterable, Identifiable, Sendable {
    case vi
    case en
    case zh

    public var id: String { rawValue }

    /// The endonym shown in the Settings picker.
    public var displayName: String {
        switch self {
        case .vi: "Tiếng Việt"
        case .en: "English"
        case .zh: "简体中文"
        }
    }

    public static let fallback: Lang = .en

    /// Map a BCP-47 tag from `Locale.preferredLanguages` onto a supported language.
    public static func preferred(_ identifier: String) -> Lang {
        let tag = identifier.lowercased()
        if tag.hasPrefix("vi") { return .vi }
        if tag.hasPrefix("zh") { return .zh }
        if tag.hasPrefix("en") { return .en }
        return .fallback
    }
}

/// A translated string is stored as its key plus interpolation variables, never
/// as rendered text — so an error shown while the language changes re-renders.
public struct L10nText: Equatable, Sendable, Hashable {
    public let key: String
    public let vars: [String: String]

    public init(_ key: String, _ vars: [String: String] = [:]) {
        self.key = key
        self.vars = vars
    }
}

/// The string table. The keys and values under the `i18n.js` section are a
/// verbatim copy of `src/ui/public/i18n.js`; `tests/i18n-parity.test.ts` fails
/// if the two ever drift. Keys after that section are native-app only.
public enum L10n {
    public static func text(_ lang: Lang, _ text: L10nText) -> String {
        render(lang, text.key, text.vars)
    }

    public static func render(_ lang: Lang, _ key: String, _ vars: [String: String] = [:]) -> String {
        var out = table(lang)[key] ?? table(.en)[key] ?? key
        for (name, value) in vars {
            out = out.replacingOccurrences(of: "{\(name)}", with: value)
        }
        return out
    }

    public static func table(_ lang: Lang) -> [String: String] {
        switch lang {
        case .vi: vi
        case .en: en
        case .zh: zh
        }
    }

    /// Tier words live under the same keys as the web (`green`/`yellow`/`red`/`blocked`).
    public static func tierKey(_ tier: Tier) -> String { tier.rawValue }

