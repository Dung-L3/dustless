export function createTranslator(code) {
  const table = STRINGS[code] ?? STRINGS.en;
  return (key, vars) => {
    let text = table[key] ?? STRINGS.en[key] ?? key;
    for (const name of Object.keys(vars ?? {})) {
      text = text.replaceAll(`{${name}}`, String(vars[name]));
    }
    return text;
  };
}